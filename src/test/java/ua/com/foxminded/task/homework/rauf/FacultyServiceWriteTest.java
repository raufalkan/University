package ua.com.foxminded.task.homework.rauf;

import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.ArgumentCaptor;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import org.slf4j.Logger;
import ua.com.foxminded.task.dao.FacultyRepository;
import ua.com.foxminded.task.domain.Faculty;
import ua.com.foxminded.task.domain.dto.FacultyDto;
import ua.com.foxminded.task.service.impl.FacultyServiceImpl;

import static org.junit.jupiter.api.Assertions.*;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;

@ExtendWith(MockitoExtension.class)
public class FacultyServiceWriteTest {

    @Mock
    private Logger logger;

    @Mock
    private FacultyRepository facultyRepository;

    @Mock
    private FacultyServiceImpl service;

    @BeforeEach
    void setUp(){
        service = new FacultyServiceImpl(logger, facultyRepository);
    }

    @Test
    @DisplayName("create returns dto with the id generated by repositıry ")
    void createReturnsDtoWithGeneratedId(){
        FacultyDto input = new FacultyDto();
        input.setTitle("Law");

        when(facultyRepository.saveAndFlush(any(Faculty.class))).thenReturn(faculty(5,"Law"));

        FacultyDto result = service.create(input);

        assertNotNull(result);
        assertEquals(5, result.getId());
    }

    @Test
    @DisplayName("create passesthe dto title to dto")
    void createPassesTitleToRepository(){
        FacultyDto dto = new FacultyDto();
        dto.setTitle("Law");

        when(facultyRepository.saveAndFlush(any(Faculty.class))).thenReturn(faculty(5,"Law"));

        service.create(dto);
        ArgumentCaptor<Faculty> captor =  ArgumentCaptor.forClass(Faculty.class);
        verify(facultyRepository).saveAndFlush(captor.capture());

        assertEquals("Law", captor.getValue().getTitle());
    }

    @Test
    @DisplayName("create return new dto leave input untouched")
    void createReturnNewDto(){
        FacultyDto facultyDto = new FacultyDto();
        facultyDto.setTitle("Law");

        when(facultyRepository.saveAndFlush(any(Faculty.class))).thenReturn(faculty(5,"Law"));

        FacultyDto result = service.create(facultyDto);

        assertNotSame(facultyDto,result);
        assertEquals(0, facultyDto.getId());
    }

    @Test
    @DisplayName("update appliye new titile and return it")
    void updateReturnDtoWithNewTitle(){
        FacultyDto input = new FacultyDto();
        input.setId(3);
        input.setTitle("Bussines");
        Faculty existing = faculty(3,"Law");

        when(facultyRepository.existsById(3)).thenReturn(true);
        when(facultyRepository.getOne(3)).thenReturn(existing);
        when(facultyRepository.saveAndFlush(existing)).thenReturn(existing);

        FacultyDto result = service.update(input);

        assertEquals("Bussines", result.getTitle());
    }

    @Test
    @DisplayName("update keep id and checks existence first")
    void updateKeepsIdAndChecksExistence() {
        FacultyDto input = new FacultyDto();
        input.setId(3);
        input.setTitle("New title");
        Faculty existing = faculty(3, "Old title");
        when(facultyRepository.existsById(3)).thenReturn(true);
        when(facultyRepository.getOne(3)).thenReturn(existing);
        when(facultyRepository.saveAndFlush(existing)).thenReturn(existing);

        FacultyDto result = service.update(input);

        assertEquals(3, result.getId());
        verify(facultyRepository).existsById(3);
    }


    private Faculty faculty(int id, String title){
        Faculty faculty = new Faculty();
        faculty.setId(id);
        faculty.setTitle(title);
        return faculty;
    }
}
